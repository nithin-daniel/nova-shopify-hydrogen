import type { Cents, MockImage, MockOption, MockProduct, MockVariant, ProductDetails } from "./types";

const usd = (dollars: number): Cents => Math.round(dollars * 100);

type VariantOverride = Partial<Omit<MockVariant, "id" | "options" | "sku">> | null;

/**
 * Builds the full variant matrix for a product. `per` overrides a combination by
 * its " / "-joined key (e.g. "Midnight / Tactile"); `null` means the combination
 * does not exist (exercises `encodedVariantExistence`).
 */
function matrix(
  n: number,
  skuPrefix: string,
  options: MockOption[],
  base: { price: number; compareAtPrice?: number; inventory: number },
  per: Record<string, VariantOverride> = {},
): MockVariant[] {
  const combos: Record<string, string>[] = options.reduce<Record<string, string>[]>(
    (acc, option) => acc.flatMap((combo) => option.values.map((v) => ({ ...combo, [option.name]: v.name }))),
    [{}],
  );
  const result: MockVariant[] = [];
  combos.forEach((combo, index) => {
    const key = options.map((o) => combo[o.name]).join(" / ");
    const override = per[key];
    if (override === null) return;
    const code = options
      .map((o) => combo[o.name].replace(/[^A-Za-z0-9]/g, "").slice(0, 3).toUpperCase())
      .join("-");
    result.push({
      id: String(48_800_000_000 + n * 100 + index),
      sku: `${skuPrefix}-${code}`,
      options: combo,
      price: usd(base.price),
      compareAtPrice: base.compareAtPrice ? usd(base.compareAtPrice) : undefined,
      inventory: base.inventory,
      ...override,
    });
  });
  return result;
}

const pid = (n: number) => String(8_800_000_000 + n);

const images = (alt: string, ...refs: [ImageKey, number][]): MockImage[] =>
  refs.map(([key, index], i) => ({ ...img(key, index), alt: i === 0 ? alt : `${alt}, view ${i + 1}` }));

